import pytest
from pydantic import ValidationError

from app.core.config import ConfigurationError, Settings, get_settings


def test_defaults_without_environment(monkeypatch: pytest.MonkeyPatch) -> None:
    for var in ("ENVIRONMENT", "DATABASE_URL", "LLM_API_KEY", "LOG_LEVEL"):
        monkeypatch.delenv(var, raising=False)

    settings = Settings(_env_file=None)

    assert settings.app_name == "BankAI"
    assert settings.environment == "development"
    assert settings.database_url.startswith("postgresql+asyncpg://")
    assert settings.llm_api_key is None
    assert settings.seed_random_seed == 42


def test_environment_variables_override_defaults(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("DATABASE_URL", "postgresql+asyncpg://u:p@db:5432/other")
    monkeypatch.setenv("LOG_LEVEL", "DEBUG")
    monkeypatch.setenv("SEED_RANDOM_SEED", "7")

    settings = Settings(_env_file=None)

    assert settings.database_url == "postgresql+asyncpg://u:p@db:5432/other"
    assert settings.log_level == "DEBUG"
    assert settings.seed_random_seed == 7


@pytest.mark.parametrize(
    ("var", "value"),
    [("ENVIRONMENT", "staging"), ("LOG_LEVEL", "LOUD"), ("SEED_RANDOM_SEED", "not-a-number")],
)
def test_invalid_values_are_rejected_at_startup(
    monkeypatch: pytest.MonkeyPatch, var: str, value: str
) -> None:
    monkeypatch.setenv(var, value)
    with pytest.raises(ValidationError):
        Settings(_env_file=None)


def test_api_key_is_masked_in_repr_and_json(monkeypatch: pytest.MonkeyPatch) -> None:
    secret = "sk-test-0123456789abcdefghij"
    monkeypatch.setenv("LLM_API_KEY", secret)

    settings = Settings(_env_file=None)

    assert settings.llm_api_key is not None
    assert settings.llm_api_key.get_secret_value() == secret
    assert secret not in repr(settings)
    assert secret not in str(settings)
    assert secret not in settings.model_dump_json()


def test_database_url_safe_hides_password(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("DATABASE_URL", "postgresql+asyncpg://bankai:s3cr3t@db:5432/bankai")

    settings = Settings(_env_file=None)

    assert "s3cr3t" not in settings.database_url_safe
    assert settings.database_url_safe == "postgresql+asyncpg://bankai:***@db:5432/bankai"


@pytest.mark.usefixtures("reset_app_state")
def test_get_settings_is_cached_until_cleared(monkeypatch: pytest.MonkeyPatch) -> None:
    first = get_settings()
    assert get_settings() is first

    monkeypatch.setenv("APP_NAME", "Changed")
    assert get_settings().app_name == first.app_name  # still cached

    get_settings.cache_clear()
    assert get_settings().app_name == "Changed"


# --- MCP settings ---------------------------------------------------------------


def test_mcp_secret_must_be_long_enough(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("MCP_AUTH_SECRET", "too-short")
    with pytest.raises(ValidationError, match="at least 32 characters"):
        Settings(_env_file=None)


def test_missing_mcp_secret_fails_loudly_instead_of_using_a_default(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.delenv("MCP_AUTH_SECRET", raising=False)
    settings = Settings(_env_file=None)

    with pytest.raises(ConfigurationError, match="MCP_AUTH_SECRET is not set"):
        settings.require_mcp_auth_secret()


def test_mcp_secret_is_available_and_masked(monkeypatch: pytest.MonkeyPatch) -> None:
    secret = "x" * 40
    monkeypatch.setenv("MCP_AUTH_SECRET", secret)
    settings = Settings(_env_file=None)

    assert settings.require_mcp_auth_secret() == secret
    assert secret not in repr(settings)


def test_mcp_allowed_hosts_parse_from_json(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("MCP_ALLOWED_HOSTS", '["mcp-server:*", "localhost:*"]')

    assert Settings(_env_file=None).mcp_allowed_hosts == ["mcp-server:*", "localhost:*"]


@pytest.mark.parametrize("var", ["MCP_AUTH_SECRET", "LLM_API_KEY"])
def test_empty_secret_from_copied_env_example_means_unset(monkeypatch: pytest.MonkeyPatch, var: str) -> None:
    monkeypatch.setenv(var, "")

    settings = Settings(_env_file=None)

    assert getattr(settings, var.lower()) is None


def test_env_example_loads_without_errors(monkeypatch: pytest.MonkeyPatch) -> None:
    """`cp .env.example .env` must give a working configuration."""
    for var in ("MCP_AUTH_SECRET", "LLM_API_KEY", "DATABASE_URL", "ENVIRONMENT"):
        monkeypatch.delenv(var, raising=False)  # real env vars would override the file

    settings = Settings(_env_file=".env.example")

    assert settings.mcp_auth_secret is None  # still has to be generated by the user
    assert settings.mcp_allowed_hosts == ["localhost:*", "127.0.0.1:*"]
