"""ORM models - the PostgreSQL schema of BankAI.

ALL DATA IN THESE TABLES IS MOCK DATA generated by ``app/database/seed.py``.
No real customers, accounts or transactions exist in this system.

Design notes:
* Money is ``Numeric(14, 2)`` mapped to Python ``Decimal`` - never ``float``,
  because binary floating point cannot represent 0.10 exactly.
* Transaction amounts are always positive; ``direction`` says whether money
  left (debit) or entered (credit) the account. A CHECK constraint enforces it.
* Primary keys are UUIDs, so IDs cannot be guessed by incrementing a number
  (relevant for the authorization tests: "show me account 2").
"""

import uuid
from datetime import datetime
from decimal import Decimal
from enum import StrEnum
from typing import Any

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    Boolean,
    CheckConstraint,
    DateTime,
    Enum,
    Float,
    ForeignKey,
    Index,
    Integer,
    Numeric,
    String,
    Text,
    UniqueConstraint,
    Uuid,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database.base import Base, JsonType
from app.models.enums import (
    AccountStatus,
    AccountType,
    Channel,
    Currency,
    EvaluationRunStatus,
    Language,
    ProductType,
    SafetyStatus,
    TransactionCategory,
    TransactionDirection,
)
from app.rag.embeddings import EMBEDDING_DIMENSIONS

Money = Numeric(14, 2)


def str_enum(enum_cls: type[StrEnum]) -> Enum:
    """Store a StrEnum as VARCHAR holding its *value* (e.g. 'checking').

    * ``values_callable``: without it SQLAlchemy would store the member *name*
      ('CHECKING'), which is surprising when you query the table by hand.
    * ``create_constraint``: adds a CHECK constraint, so the database itself
      rejects invalid values - even from raw SQL that bypasses Python.
    """
    return Enum(
        enum_cls,
        native_enum=False,
        create_constraint=True,
        length=32,
        values_callable=lambda members: [member.value for member in members],
        validate_strings=True,
    )


def created_at_column() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)


class User(Base):
    """A (mock) bank customer."""

    __tablename__ = "users"

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    customer_number: Mapped[str] = mapped_column(String(16), unique=True)
    full_name: Mapped[str] = mapped_column(String(120))
    email: Mapped[str] = mapped_column(String(255), unique=True)
    preferred_language: Mapped[Language] = mapped_column(str_enum(Language), default=Language.ENGLISH)
    created_at: Mapped[datetime] = created_at_column()

    accounts: Mapped[list["Account"]] = relationship(back_populates="user", cascade="all, delete-orphan")


class Account(Base):
    """A (mock) bank account owned by exactly one user."""

    __tablename__ = "accounts"
    __table_args__ = (CheckConstraint("balance >= 0", name="balance_non_negative"),)

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True)
    # IBAN-shaped but deliberately invalid (check digits "00", bank code "MOCK").
    account_number: Mapped[str] = mapped_column(String(34), unique=True)
    name: Mapped[str] = mapped_column(String(80))
    account_type: Mapped[AccountType] = mapped_column(str_enum(AccountType))
    currency: Mapped[Currency] = mapped_column(str_enum(Currency))
    balance: Mapped[Decimal] = mapped_column(Money, default=Decimal("0.00"))
    status: Mapped[AccountStatus] = mapped_column(str_enum(AccountStatus), default=AccountStatus.ACTIVE)
    opened_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[datetime] = created_at_column()

    user: Mapped[User] = relationship(back_populates="accounts")
    transactions: Mapped[list["Transaction"]] = relationship(
        back_populates="account", cascade="all, delete-orphan"
    )


class Transaction(Base):
    """A booked (mock) movement of money on an account."""

    __tablename__ = "transactions"
    __table_args__ = (
        CheckConstraint("amount > 0", name="amount_positive"),
        # Most queries are "transactions of account X between dates A and B".
        Index("ix_transactions_account_id_booked_at", "account_id", "booked_at"),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    account_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("accounts.id", ondelete="CASCADE"))
    direction: Mapped[TransactionDirection] = mapped_column(str_enum(TransactionDirection))
    amount: Mapped[Decimal] = mapped_column(Money)
    currency: Mapped[Currency] = mapped_column(str_enum(Currency))
    category: Mapped[TransactionCategory] = mapped_column(str_enum(TransactionCategory), index=True)
    merchant: Mapped[str] = mapped_column(String(120))
    description: Mapped[str] = mapped_column(String(255))
    booked_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[datetime] = created_at_column()

    account: Mapped[Account] = relationship(back_populates="transactions")


class BankingProduct(Base):
    """A (mock) product from the bank's catalogue: cards, loans, deposits...

    Loan/deposit rates live here so the calculator tool reads them from the
    database instead of the LLM inventing an interest rate.
    """

    __tablename__ = "banking_products"

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    code: Mapped[str] = mapped_column(String(40), unique=True)
    name: Mapped[str] = mapped_column(String(120))
    product_type: Mapped[ProductType] = mapped_column(str_enum(ProductType))
    description: Mapped[str] = mapped_column(Text)
    currency: Mapped[Currency] = mapped_column(str_enum(Currency), default=Currency.GEL)
    interest_rate_pct: Mapped[Decimal | None] = mapped_column(Numeric(5, 2))  # annual, in percent
    monthly_fee: Mapped[Decimal | None] = mapped_column(Numeric(10, 2))
    min_amount: Mapped[Decimal | None] = mapped_column(Money)
    max_amount: Mapped[Decimal | None] = mapped_column(Money)
    min_term_months: Mapped[int | None] = mapped_column(Integer)
    max_term_months: Mapped[int | None] = mapped_column(Integer)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)
    created_at: Mapped[datetime] = created_at_column()


class ConversationLog(Base):
    """One row per assistant turn - the audit trail of the agent.

    ``user_input`` and ``response_text`` are stored after secret redaction.
    """

    __tablename__ = "conversation_logs"

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    request_id: Mapped[str] = mapped_column(String(64), index=True)
    conversation_id: Mapped[str] = mapped_column(String(64), index=True)
    user_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"), index=True)
    channel: Mapped[Channel] = mapped_column(str_enum(Channel), default=Channel.TEXT)
    user_input: Mapped[str] = mapped_column(Text)
    detected_intent: Mapped[str | None] = mapped_column(String(40))
    selected_tool: Mapped[str | None] = mapped_column(String(64))
    tool_arguments: Mapped[dict[str, Any] | None] = mapped_column(JsonType)
    tool_latency_ms: Mapped[float | None] = mapped_column(Float)
    llm_latency_ms: Mapped[float | None] = mapped_column(Float)
    total_latency_ms: Mapped[float | None] = mapped_column(Float)
    response_text: Mapped[str | None] = mapped_column(Text)
    # NULL only when the request failed before the safety layer ran.
    safety_status: Mapped[SafetyStatus | None] = mapped_column(str_enum(SafetyStatus))
    safety_flags: Mapped[list[str]] = mapped_column(JsonType, default=list)
    error_code: Mapped[str | None] = mapped_column(String(64))
    created_at: Mapped[datetime] = created_at_column()


class EvaluationRun(Base):
    """One execution of the evaluation suite. Metrics are computed, never typed in."""

    __tablename__ = "evaluation_runs"

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    status: Mapped[EvaluationRunStatus] = mapped_column(
        str_enum(EvaluationRunStatus), default=EvaluationRunStatus.RUNNING
    )
    # Which brain was evaluated: the deterministic offline "fake" provider or a real LLM.
    llm_provider: Mapped[str] = mapped_column(String(32))
    model_name: Mapped[str | None] = mapped_column(String(64))
    dataset_name: Mapped[str] = mapped_column(String(64))
    dataset_version: Mapped[str] = mapped_column(String(64))  # content hash of the dataset
    total_cases: Mapped[int] = mapped_column(Integer, default=0)
    passed_cases: Mapped[int] = mapped_column(Integer, default=0)
    summary: Mapped[dict[str, Any]] = mapped_column(JsonType, default=dict)
    started_at: Mapped[datetime] = created_at_column()
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    results: Mapped[list["EvaluationResult"]] = relationship(
        back_populates="run", cascade="all, delete-orphan"
    )


class EvaluationResult(Base):
    """The outcome of a single evaluation case within a run."""

    __tablename__ = "evaluation_results"
    __table_args__ = (UniqueConstraint("run_id", "case_id", name="uq_evaluation_results_run_id_case_id"),)

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    run_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("evaluation_runs.id", ondelete="CASCADE"), index=True
    )
    case_id: Mapped[str] = mapped_column(String(64))
    category: Mapped[str] = mapped_column(String(32), index=True)
    input_text: Mapped[str] = mapped_column(Text)
    expected_behavior: Mapped[str] = mapped_column(String(64))
    actual_behavior: Mapped[str | None] = mapped_column(String(64))
    expected_intent: Mapped[str | None] = mapped_column(String(40))
    actual_intent: Mapped[str | None] = mapped_column(String(40))
    expected_tool: Mapped[str | None] = mapped_column(String(64))
    actual_tool: Mapped[str | None] = mapped_column(String(64))
    passed: Mapped[bool] = mapped_column(Boolean)
    scores: Mapped[dict[str, Any]] = mapped_column(JsonType, default=dict)
    failure_reasons: Mapped[list[str]] = mapped_column(JsonType, default=list)
    response_text: Mapped[str | None] = mapped_column(Text)
    latency_ms: Mapped[float | None] = mapped_column(Float)
    created_at: Mapped[datetime] = created_at_column()

    run: Mapped[EvaluationRun] = relationship(back_populates="results")


class KnowledgeChunk(Base):
    """One section of a knowledge-base document with its embedding (RAG).

    The ``embedding`` column is a pgvector ``vector(768)``; the HNSW index makes
    nearest-neighbour search by cosine distance fast as the knowledge base grows.
    """

    __tablename__ = "knowledge_chunks"
    __table_args__ = (
        UniqueConstraint("embedding_model", "chunk_id", name="uq_knowledge_chunks_embedding_model_chunk_id"),
        Index(
            "ix_knowledge_chunks_embedding_hnsw",
            "embedding",
            postgresql_using="hnsw",
            postgresql_ops={"embedding": "vector_cosine_ops"},
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    chunk_id: Mapped[str] = mapped_column(String(200))
    source: Mapped[str] = mapped_column(String(120))
    title: Mapped[str] = mapped_column(String(200))
    section: Mapped[str] = mapped_column(String(200))
    content: Mapped[str] = mapped_column(Text)
    content_hash: Mapped[str] = mapped_column(String(64))
    embedding_model: Mapped[str] = mapped_column(String(100), index=True)
    embedding: Mapped[Any] = mapped_column(Vector(EMBEDDING_DIMENSIONS))
    created_at: Mapped[datetime] = created_at_column()
